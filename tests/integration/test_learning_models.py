def test_one_wrong_prediction_does_not_change_the_active_method(boss):
    registry.ensure_registry()
    make_csp()
    p = stored_prediction(estimate=d(2026, 2, 3), first_seen=d(2026, 2, 1), predicted="5000")
    stored_outcome(p, 1000, event=d(2026, 2, 8))  # wildly wrong
    assert registry.active_model().name == "movement"
    assert not ModelEvent.objects.filter(kind__in=["PROMOTED", "ROLLED_BACK"]).exists()
    assert not CandidateEvaluation.objects.exists()  # nothing retrained or re-evaluated on its own


# ------------------------------------------------------------------ rollback
def test_rollback_restores_the_method_that_was_active_before(promotable, boss):
    registry.promote(promotable, boss, "Beat the active rule in every held-out refresh.")
    event = registry.rollback(boss, "New statements showed the promoted rule drifting.")
    assert event.kind == "ROLLED_BACK" and event.model.name == "movement"
    assert registry.active_model().name == "movement"
    flow_only = ModelVersion.objects.get(name="flow_only")
    assert flow_only.stage == "CANDIDATE"  # it must be evaluated again before any new promotion
    assert event.previous.name == "flow_only" and "restored_verdict" in event.snapshot
    assert [e.kind for e in registry.history()][:2] == ["ROLLED_BACK", "PROMOTED"]


def test_rollback_needs_a_superuser_a_reason_and_a_promotion_to_undo(promotable, boss):
    with pytest.raises(RegistryError, match="no promotion"):
        registry.rollback(boss, "A perfectly good written reason.")
    registry.promote(promotable, boss, "Beat the active rule in every held-out refresh.")
    staff = get_user_model().objects.create_user(username="s2", password="x", is_staff=True)
    with pytest.raises(RegistryError, match="superuser"):
        registry.rollback(staff, "A perfectly good written reason.")
    with pytest.raises(RegistryError, match="reason"):
        registry.rollback(boss, "no")
    assert registry.active_model().name == "flow_only"
    registry.rollback(boss, "A perfectly good written reason.")
    with pytest.raises(RegistryError, match="no promotion"):
        registry.rollback(boss, "A perfectly good written reason.")  # nothing left to undo


def test_model_history_cannot_be_edited_or_removed(promotable, boss):
    event = registry.promote(promotable, boss, "Beat the active rule in every held-out refresh.")
    event.reason = "rewritten"
    with pytest.raises(ImmutableRecord):
        event.save()
    with pytest.raises(ImmutableRecord):
        event.delete()
    assert ModelEvent.objects.get(pk=event.pk).reason.startswith("Beat")


def test_the_promote_command_goes_through_the_same_checks(promotable, boss):
    from django.core.management import call_command
    from django.core.management.base import CommandError

    with pytest.raises(CommandError, match="reason"):
        call_command("promote_model", "flow_only", actor="boss", reason="no")
    with pytest.raises(CommandError, match="No registered method"):
        call_command("promote_model", "nope", actor="boss", reason="A perfectly good reason.")
    call_command("promote_model", "flow_only", actor="boss",
                 reason="Beat the active rule in every held-out refresh.")
    assert registry.active_model().name == "flow_only"
    call_command("promote_model", rollback=True, actor="boss", reason="Rolling back for review.")
    assert registry.active_model().name == "movement"
