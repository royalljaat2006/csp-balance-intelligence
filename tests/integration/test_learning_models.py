"""
Candidate methods compared on SBI refreshes in date order, and the audited route from candidate to
active: recommendation only when the pre-declared criteria are met, promotion only by an active
superuser with a reason, rollback, and no automatic change after one wrong prediction.

SYNTHETIC history (invented CSPs and amounts). The rules are exact by construction, so these tests
show how the machinery decides; they say nothing about how well any rule fits real SBI data.
"""

