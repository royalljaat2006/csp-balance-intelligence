@pytest.fixture
def promotable():
    """flow_only made runnable live and given a RECOMMENDED evaluation (the criteria themselves
    are exercised above; here the registry's own rules are under test)."""
    history("flow_only", count_growth=10)
    verdicts()
    mv = ModelVersion.objects.get(name="flow_only")
    mv.live_supported = True
    mv.save(update_fields=["live_supported"])
    assert registry.latest_evaluation(mv).verdict == V.RECOMMENDED
    return mv


def test_a_recommended_live_candidate_is_promoted_by_a_superuser_with_a_reason(promotable, boss):
    event = registry.promote(promotable, boss, "Beat the active rule in every held-out refresh.")
    promotable.refresh_from_db()
    assert promotable.stage == "ACTIVE" and registry.active_model().pk == promotable.pk
    assert ModelVersion.objects.get(name="movement").stage == "RETIRED"
    assert ModelVersion.objects.filter(in_registry=True, stage="ACTIVE").count() == 1
    assert event.kind == "PROMOTED" and event.actor == "boss" and event.previous.name == "movement"
    assert event.evaluation.verdict == V.RECOMMENDED and event.snapshot["previous"] == "movement"
    assert event.snapshot["criteria"] and event.snapshot["previous_verdict"]
    assert registry.history()[0].pk == event.pk


@pytest.mark.parametrize("make_user,message", [
    (lambda U: U.objects.create_user(username="s", password="x", is_staff=True), "superuser"),
    (lambda U: U.objects.create_user(username="i", password="x", is_superuser=True,
                                     is_active=False), "superuser"),
    (lambda U: None, "superuser"),
])
def test_only_an_active_superuser_may_change_the_active_method(promotable, make_user, message):
    user = make_user(get_user_model())
    with pytest.raises(RegistryError, match=message):
        registry.promote(promotable, user, "A perfectly good written reason.")
    assert registry.active_model().name == "movement"
    assert not ModelEvent.objects.filter(kind="PROMOTED").exists()


def test_a_written_reason_is_required(promotable, boss):
    for reason in ("", "   ", "ok"):
        with pytest.raises(RegistryError, match="reason"):
            registry.promote(promotable, boss, reason)
    assert registry.active_model().name == "movement"


def test_each_promotion_condition_blocks_on_its_own(promotable, boss):
    reason = "A perfectly good written reason."
    # not live
    promotable.live_supported = False
    promotable.save(update_fields=["live_supported"])
    with pytest.raises(RegistryError, match="cannot run this method"):
        registry.promote(promotable, boss, reason)
    promotable.live_supported = True
    # blocked by a business rule
    promotable.blocked_reason = "Business rule."
    promotable.save(update_fields=["live_supported", "blocked_reason"])
    with pytest.raises(RegistryError, match="Blocked"):
        registry.promote(promotable, boss, reason)
    promotable.blocked_reason = ""
    promotable.save(update_fields=["blocked_reason"])
    # not a candidate
    active = registry.active_model()
    with pytest.raises(RegistryError, match="candidate"):
        registry.promote(active, boss, reason)
    # the evaluation is stale
    stale = registry.latest_evaluation(promotable).created_at + dt.timedelta(days=8)
    assert any("evaluate again" in p for p in registry.promotion_problems(promotable, now=stale))
    assert registry.promotion_problems(promotable) == []


def test_an_unevaluated_or_not_recommended_method_cannot_be_promoted(boss):
    registry.ensure_registry()
    fo = ModelVersion.objects.get(name="flow_only")
