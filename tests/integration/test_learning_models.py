def test_evaluating_never_changes_which_method_is_active():
    history("flow_only", count_growth=10)
    before = {m.name: m.stage for m in registry.registered()} if registry.registered() else None
    verdicts()
    after = {m.name: m.stage for m in registry.registered()}
    assert after["movement"] == "ACTIVE" and after["flow_only"] == "CANDIDATE"
    assert before is None or before == after
    assert not ModelEvent.objects.filter(kind__in=["PROMOTED", "ROLLED_BACK"]).exists()


